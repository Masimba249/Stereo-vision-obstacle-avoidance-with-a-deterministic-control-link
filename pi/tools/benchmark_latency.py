#!/usr/bin/env python3
"""Measure the per-stage latency budget and publish the numbers.

Runs the real pipeline against the behavioural node over the in-process bus,
at several working resolutions, and emits a markdown report.  The point is to
make the resolution/latency trade explicit rather than asserting a frame rate.

    python3 pi/tools/benchmark_latency.py --frames 120 --out docs/latency-budget.md
"""

from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
import threading
import time
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from esp32_sim import Esp32NodeSim  # noqa: E402
from stereolink.canlink import LoopbackTransport  # noqa: E402
from stereolink.config import AppConfig  # noqa: E402
from stereolink.latency import STAGES  # noqa: E402
from stereolink.pipeline import Pipeline  # noqa: E402

RESOLUTIONS = [(320, 180), (480, 270), (640, 360), (848, 480)]


def cpu_model() -> str:
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            for key in ("model name", "Model"):
                if line.startswith(key):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or platform.machine()


def run_one(width: int, height: int, frames: int, num_disp: int,
            process_hz: float) -> dict:
    cfg = AppConfig()
    cfg.camera.source = "synthetic"
    cfg.camera.capture_width = 1280
    cfg.camera.capture_height = 720
    cfg.camera.process_hz = process_hz
    cfg.stereo.work_width = width
    cfg.stereo.work_height = height
    cfg.stereo.num_disparities = num_disp
    cfg.can.interface = "loopback"
    cfg.can.send_sync = False
    cfg.mqtt.enabled = False
    cfg.opcua.enabled = False
    cfg.latency.window = frames + 50
    cfg.latency.report_every_s = 0
    cfg.latency.report_path = ""
    cfg.latency.markdown_path = ""

    bus = LoopbackTransport()
    node = Esp32NodeSim(bus.endpoint("node"), node_id=cfg.can.node_id)
    pipeline = Pipeline(cfg, transport=bus.endpoint("master"))

    node.start()
    t0 = time.monotonic()
    pipeline.run(max_frames=frames)
    wall = time.monotonic() - t0
    node.stop()

    snap = pipeline.latency.snapshot()
    snap["resolution"] = f"{width}x{height}"
    snap["num_disparities"] = num_disp
    snap["frames"] = pipeline.stats.frames
    snap["wall_s"] = round(wall, 2)
    snap["achieved_hz"] = round(pipeline.stats.frames / wall, 2) if wall else 0.0
    return snap


def stage_table(snap: dict) -> list[str]:
    rows = {r["stage"]: r for r in snap["stages"]}
    lines = [
        "| Stage | n | mean ms | p50 ms | p95 ms | p99 ms | max ms |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for stage in STAGES:
        r = rows.get(stage)
        if r is None:
            continue
        lines.append(f"| `{stage}` | {r['count']} | {r['mean_ms']:.2f} | "
                     f"{r['p50_ms']:.2f} | {r['p95_ms']:.2f} | {r['p99_ms']:.2f} "
                     f"| {r['max_ms']:.2f} |")
    for key, label in (("end_to_end", "**capture → echo (end-to-end)**"),
                       ("round_trip", "**tx → echo (link round trip)**")):
        r = snap["totals"].get(key)
        if r:
            lines.append(f"| {label} | {r['count']} | {r['mean_ms']:.2f} | "
                         f"{r['p50_ms']:.2f} | {r['p95_ms']:.2f} | "
                         f"{r['p99_ms']:.2f} | {r['max_ms']:.2f} |")
    return lines


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--frames", type=int, default=100)
    ap.add_argument("--hz", type=float, default=10.0)
    ap.add_argument("--num-disparities", type=int, default=96)
    ap.add_argument("--out", default="docs/latency-budget.md")
    ap.add_argument("--json-out", default="reports/latency-benchmark.json")
    ap.add_argument("--quick", action="store_true",
                    help="only the default 640x360 configuration")
    args = ap.parse_args()

    import logging
    logging.basicConfig(level=logging.ERROR)

    resolutions = [(640, 360)] if args.quick else RESOLUTIONS
    results = []
    for w, h in resolutions:
        print(f"running {w}x{h} for {args.frames} frames ...", flush=True)
        results.append(run_one(w, h, args.frames, args.num_disparities, args.hz))

    host = f"{cpu_model()}, Python {platform.python_version()}, {platform.system()}"
    try:
        import cv2
        host += f", OpenCV {cv2.__version__}"
    except ImportError:
        pass

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Latency budget — measured",
        "",
        "Generated by `pi/tools/benchmark_latency.py`. Regenerate after any",
        "change to the vision stages, and do not hand-edit the tables.",
        "",
        f"- Generated: {now}",
        f"- Host: {host}",
        f"- Frames per configuration: {args.frames} at {args.hz} Hz",
        f"- `numDisparities`: {args.num_disparities}, SGBM 3-way mode",
        "- Camera: synthetic rig (deterministic scene, 1280×720 per eye)",
        "- Link: in-process loopback against the behavioural node model",
        "",
        "## How each stage is measured",
        "",
        "The Pi and the ESP32 have unrelated clocks, so nothing here subtracts",
        "a timestamp taken on one from a timestamp taken on the other. Instead",
        "each setpoint carries a one-byte `seq`; the node echoes it back and",
        "separately reports its own local receive→apply span. That gives a",
        "per-stage breakdown on the Pi, a measured actuation span on the node,",
        "and a round trip that bounds everything in between.",
        "",
        "| Stage | What it covers |",
        "|---|---|",
        "| `capture` | Waiting for and retrieving the next frame. Bounded below by `1/fps`: at 30 fps a ~16 ms median is the sensor cadence, not processing cost. |",
        "| `decode` | Eye split and downscale to the working resolution. |",
        "| `rectify` | `cv2.remap` of both eyes with pre-computed fixed-point maps. |",
        "| `disparity` | `StereoSGBM.compute` — the dominant cost. |",
        "| `depth` | Disparity → metric depth (`Z = fB/d`). |",
        "| `obstacle` | Depth → per-column free-space profile, ground rejection. |",
        "| `plan` | Free-space profile → `(v, ω)` setpoint. |",
        "| `encode_tx` | PDO encode and handoff to the CAN socket. |",
        "| `link_to_node` | Derived: `(round_trip − node_apply) / 2`. |",
        "| `node_apply` | Reported by the node: TWAI receive → PWM register write. |",
        "",
        "## Results by working resolution",
        "",
    ]

    for snap in results:
        lines += [f"### {snap['resolution']}", ""]
        lines += [f"Achieved {snap['achieved_hz']:.1f} Hz over "
                  f"{snap['frames']} frames "
                  f"({snap['echoes_matched']} echoes matched, "
                  f"{snap['echoes_lost']} lost).", ""]
        lines += stage_table(snap)
        lines += ["", f"Sum of stage medians: "
                      f"**{snap['sum_of_stage_p50_ms']:.2f} ms**", ""]

    lines += [
        "## Reading these numbers",
        "",
        "**`disparity` dominates, and it scales with pixels × disparity range.**",
        "Working resolution is therefore the main latency control, which is why",
        "it is a config field and not a constant. Halving the working width",
        "roughly quarters SGBM cost, at the price of angular resolution on",
        "small obstacles.",
        "",
        "**The sum of stage medians is not the median end-to-end.** Stages do",
        "not peak in the same frame, so adding medians overstates the typical",
        "path and understates the tail. Both are reported; for a safety",
        "argument use the p99 end-to-end, not the sum.",
        "",
        "**`capture` is dominated by waiting, not working.** It is bounded",
        "below by the sensor period. It appears in the budget because the",
        "obstacle is that old by the time we see it — but it is not work the",
        "Pi can optimise away.",
        "",
        "**`link_to_node` here is not CAN wire time.** Over the loopback",
        "transport it measures Python thread scheduling. On a real 500 kbit/s",
        "bus an 8-byte frame is ~230 µs of wire time plus arbitration; the",
        "figure to trust on hardware is `node_apply`, which the node measures",
        "against its own clock.",
        "",
        "## What this means for stopping distance",
        "",
        "The vision path is *advisory*. Worst-case reaction to something the",
        "camera sees is roughly p99 end-to-end plus one control period; at",
        "0.7 m/s that is a few centimetres of travel. The guarantee that",
        "matters is not this number, though — it is the node's own failsafe,",
        "which does not depend on the Pi being alive at all. See",
        "[failsafe.md](failsafe.md).",
        "",
    ]

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {out}")

    if args.json_out:
        jp = Path(args.json_out)
        jp.parent.mkdir(parents=True, exist_ok=True)
        jp.write_text(json.dumps(results, indent=2), encoding="utf-8")
        print(f"wrote {jp}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
